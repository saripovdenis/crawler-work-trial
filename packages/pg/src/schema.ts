import type { DatabaseSync } from './sync.js';

// Two schemas in one database: crawl_budget holds the crawler's rows and
// reconciler holds the external sample. Table and column names are unchanged
// from the SQLite files, so the queries read the same. Millisecond timestamps stay integers; rowid is a real column.
// Statements are separated by a line holding only "--" because function
// bodies contain semicolons.
const statements = `
CREATE SCHEMA IF NOT EXISTS crawl_budget
--
CREATE OR REPLACE FUNCTION crawl_budget.json_extract(doc text, path text) RETURNS text LANGUAGE sql IMMUTABLE
  AS $$ SELECT doc::jsonb #>> string_to_array(substr(path, 3), '.') $$
--
CREATE OR REPLACE FUNCTION crawl_budget.unixepoch(value text) RETURNS bigint LANGUAGE sql STABLE
  AS $$ SELECT floor(extract(epoch FROM value::timestamptz))::bigint $$
--
CREATE OR REPLACE FUNCTION crawl_budget.sum_boolean_step(total bigint, value boolean) RETURNS bigint LANGUAGE sql IMMUTABLE
  AS $$ SELECT CASE WHEN value IS NULL THEN total ELSE coalesce(total, 0) + value::int END $$
--
CREATE OR REPLACE AGGREGATE crawl_budget.sum(boolean) (SFUNC = crawl_budget.sum_boolean_step, STYPE = bigint)
--
CREATE TABLE IF NOT EXISTS crawl_budget.meta (key text PRIMARY KEY, value text NOT NULL)
--
CREATE TABLE IF NOT EXISTS crawl_budget.sites (domain text PRIMARY KEY, started bigint NOT NULL, cooldown bigint NOT NULL DEFAULT 0)
--
CREATE TABLE IF NOT EXISTS crawl_budget.requests (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, domain text NOT NULL, url text NOT NULL, purpose text NOT NULL,
  started bigint NOT NULL, finished bigint, status bigint, error text, body_hash text, headers text)
--
CREATE INDEX IF NOT EXISTS requests_time ON crawl_budget.requests (domain, started)
--
CREATE INDEX IF NOT EXISTS requests_url ON crawl_budget.requests (url, id)
--
CREATE INDEX IF NOT EXISTS requests_started ON crawl_budget.requests (started)
--
CREATE TABLE IF NOT EXISTS crawl_budget.robots (origin text PRIMARY KEY, body text NOT NULL, expires bigint NOT NULL)
--
CREATE TABLE IF NOT EXISTS crawl_budget.sources (
  url text PRIMARY KEY, domain text NOT NULL, kind text NOT NULL, depth bigint DEFAULT 0, next_poll bigint DEFAULT 0,
  polls bigint DEFAULT 0, errors bigint DEFAULT 0, discovered bigint DEFAULT 0, etag text, modified text, last_error text)
--
CREATE TABLE IF NOT EXISTS crawl_budget.candidates (
  rowid bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE, url text PRIMARY KEY, domain text NOT NULL, source text NOT NULL,
  discovered bigint NOT NULL, published_hint text, priority bigint NOT NULL, state text DEFAULT 'pending',
  attempts bigint DEFAULT 0, next_attempt bigint DEFAULT 0, last_error text)
--
CREATE INDEX IF NOT EXISTS candidate_queue ON crawl_budget.candidates (domain, state, priority, discovered)
--
CREATE TABLE IF NOT EXISTS crawl_budget.articles (
  rowid bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE, canonical_url text PRIMARY KEY, domain text NOT NULL,
  discovered bigint NOT NULL, fetched bigint NOT NULL, published text, classification text NOT NULL,
  fingerprint text NOT NULL, payload text NOT NULL)
--
CREATE INDEX IF NOT EXISTS article_fingerprint ON crawl_budget.articles (fingerprint)
--
CREATE INDEX IF NOT EXISTS article_fetched ON crawl_budget.articles (fetched)
--
CREATE TABLE IF NOT EXISTS crawl_budget.crawl_tasks (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, domain text NOT NULL, url text NOT NULL, purpose text NOT NULL,
  priority bigint NOT NULL DEFAULT 0, next_crawl_at bigint NOT NULL, state text NOT NULL DEFAULT 'ready',
  current_url text NOT NULL, hops bigint NOT NULL DEFAULT 0, headers text NOT NULL DEFAULT '{}',
  parent_id bigint, origin text, UNIQUE (url, purpose))
--
CREATE INDEX IF NOT EXISTS crawl_tasks_due ON crawl_budget.crawl_tasks (state, next_crawl_at, priority DESC)
--
CREATE INDEX IF NOT EXISTS crawl_tasks_domain_due ON crawl_budget.crawl_tasks (domain, purpose, state, next_crawl_at)
--
CREATE TABLE IF NOT EXISTS crawl_budget.attempt_assignments (
  attempt_id text PRIMARY KEY, request_id bigint NOT NULL UNIQUE, task_id bigint NOT NULL, domain text NOT NULL,
  worker_id text NOT NULL, claim_id text NOT NULL UNIQUE, lease_token text NOT NULL, start_by bigint NOT NULL,
  lease_until bigint NOT NULL, assignment text NOT NULL, terminal text, completion text,
  processing text NOT NULL DEFAULT 'waiting', process_after bigint NOT NULL DEFAULT 0,
  process_errors bigint NOT NULL DEFAULT 0, process_error text)
--
CREATE UNIQUE INDEX IF NOT EXISTS active_domain_assignment ON crawl_budget.attempt_assignments (domain) WHERE terminal IS NULL
--
CREATE INDEX IF NOT EXISTS attempts_processing ON crawl_budget.attempt_assignments (processing, process_after)
--
CREATE INDEX IF NOT EXISTS attempts_task ON crawl_budget.attempt_assignments (task_id)
--
CREATE TABLE IF NOT EXISTS crawl_budget.scheduler_domains (domain text PRIMARY KEY, articles_since_poll bigint NOT NULL DEFAULT 2)
--
CREATE TABLE IF NOT EXISTS crawl_budget.article_aliases (
  alias_url text PRIMARY KEY, target_url text NOT NULL, domain text NOT NULL, kind text NOT NULL,
  request_id bigint NOT NULL, observed bigint NOT NULL, expires bigint NOT NULL)
--
CREATE INDEX IF NOT EXISTS article_alias_target ON crawl_budget.article_aliases (target_url)
--
-- Budget migration is atomic and one-off. Keep cooldown for old-release rollback.
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='crawl_budget' AND table_name='sites' AND column_name='next_available_at') THEN
    ALTER TABLE crawl_budget.sites ADD COLUMN next_available_at bigint NOT NULL DEFAULT 0;
    -- A full minute after the last possible dispatch safely drains any old burst.
    UPDATE crawl_budget.sites s SET next_available_at=greatest(s.cooldown,coalesce((
      SELECT max(greatest(coalesce(r.finished,r.started+35000),r.started+35000))+60020
      FROM crawl_budget.requests r WHERE r.domain=s.domain),0));
  END IF;
END $$
--
CREATE INDEX IF NOT EXISTS sites_available ON crawl_budget.sites (next_available_at)
--
ALTER TABLE crawl_budget.requests ADD COLUMN IF NOT EXISTS sent_at bigint
--
ALTER TABLE crawl_budget.requests ADD COLUMN IF NOT EXISTS budget_spacing_ms bigint
--
ALTER TABLE crawl_budget.requests ADD COLUMN IF NOT EXISTS budget_delay_ms bigint
--
CREATE TABLE IF NOT EXISTS crawl_budget.budget_origins (origin text PRIMARY KEY, last_started bigint NOT NULL, next_available_at bigint NOT NULL)
--
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM crawl_budget.meta WHERE key='budget-origins-v1') THEN
    INSERT INTO crawl_budget.budget_origins(origin,last_started,next_available_at)
      SELECT substring(url from '^(https?://[^/]+)'),max(greatest(coalesce(finished,started+35000),started+35000)),
        max(greatest(coalesce(finished,started+35000),started+35000))
      FROM crawl_budget.requests WHERE url ~ '^https?://' GROUP BY substring(url from '^(https?://[^/]+)')
      ON CONFLICT(origin) DO NOTHING;
    INSERT INTO crawl_budget.meta(key,value) VALUES ('budget-origins-v1','done');
  END IF;
END $$
--
CREATE SCHEMA IF NOT EXISTS reconciler
--
DO $$ DECLARE name text; BEGIN
  -- The external sample used to share crawl_budget. Moving a table keeps its rows, indexes and sequences.
  FOREACH name IN ARRAY ARRAY['provider_state','provider_schedule','provider_runs','external_sightings','monitor_meta','audit_candidates'] LOOP
    IF to_regclass('crawl_budget.' || name) IS NOT NULL AND to_regclass('reconciler.' || name) IS NULL THEN
      EXECUTE format('ALTER TABLE crawl_budget.%I SET SCHEMA reconciler', name);
    END IF;
  END LOOP;
END $$
--
CREATE TABLE IF NOT EXISTS reconciler.provider_state (
  provider text PRIMARY KEY, enabled bigint, daily_limit bigint, total_limit bigint, next_call bigint DEFAULT 0, note text)
--
CREATE TABLE IF NOT EXISTS reconciler.provider_schedule (
  provider text, site text, next_poll bigint, last_success bigint, PRIMARY KEY (provider, site))
--
CREATE TABLE IF NOT EXISTS reconciler.provider_runs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, provider text, site text, started_at bigint, finished_at bigint,
  status text, result_count bigint DEFAULT 0, accepted_count bigint DEFAULT 0, truncated bigint DEFAULT 0,
  quota_used bigint DEFAULT 1, cost_usd double precision, window_start bigint, window_end bigint, error text)
--
CREATE INDEX IF NOT EXISTS provider_runs_quota ON reconciler.provider_runs (provider, started_at)
--
CREATE TABLE IF NOT EXISTS reconciler.external_sightings (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, provider text, site text, item_key text, url_raw text, url_key text,
  title text, title_key text, provider_published_at bigint, provider_first_seen_at bigint, observed_at bigint,
  last_observed_at bigint, run_id bigint, UNIQUE (provider, site, item_key))
--
CREATE INDEX IF NOT EXISTS sightings_time ON reconciler.external_sightings (observed_at, site, provider)
--
CREATE INDEX IF NOT EXISTS sightings_published ON reconciler.external_sightings (provider_published_at)
--
ALTER TABLE reconciler.external_sightings ADD COLUMN IF NOT EXISTS source_host text
--
CREATE TABLE IF NOT EXISTS reconciler.monitor_meta (key text PRIMARY KEY, value text)
--
CREATE TABLE IF NOT EXISTS reconciler.audit_candidates (
  rowid bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE, url_key text PRIMARY KEY, url text, domain text,
  created_at bigint, state text DEFAULT 'pending')
`;
export const schemaStatements = statements.split(/\n--\n/).map(statement => statement.trim()).filter(Boolean);

// Idempotent. Callers that only read never run this.
export function ensureSchema(db: DatabaseSync) {
  // Two services can start together; creating the same objects must not race.
  db.call({ text: 'SELECT pg_advisory_lock(741101)' });
  try { for (const statement of schemaStatements) db.call({ text: statement }); }
  finally { db.call({ text: 'SELECT pg_advisory_unlock(741101)' }); }
}
